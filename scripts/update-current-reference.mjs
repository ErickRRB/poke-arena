import fs from 'node:fs';
import { CARDS } from '../dist/engine.js';
import { CARD_EQUIVALENTS } from '../dist/card-equivalents.js';

// Reviewable source-to-game conversion. Never copy a total attack into each burst.
const source=JSON.parse(fs.readFileSync(new URL('../docs/CLASH-REFERENCE-2026-11-14.json',import.meta.url),'utf8'));
const overrides={},audit=[];
const comparable=new Set(['zubat','diglettHorde','sandshrew','beedrill','duskull','machamp','feraligatr','starmie','sharpedo']);
const speedTier=new Map([[18,21.6],[26,28.8],[32,43.2],[40,57.6],[21.6,21.6],[28.8,28.8],[43.2,43.2],[57.6,57.6]]);
for(const [key,card] of Object.entries(CARDS)){
  const equivalent=CARD_EQUIVALENTS[key],profile=source.profiles[equivalent?.reference],stats=profile?.stats;
  const patch={};
  if(!card.spell){patch.deployTime=1;if(speedTier.has(card.speed))patch.speed=speedTier.get(card.speed);}
  const direct=equivalent?.similarity==='equivalent'||comparable.has(key);
  if(stats){
    if(!card.spell){
      if(stats.deployTimeSeconds!==null)patch.deployTime=stats.deployTimeSeconds;
      if(stats.firstAttackDelaySeconds!==null)patch.windup=stats.firstAttackDelaySeconds;
      if(direct){
        if(stats.hp!==null)patch.hp=stats.hp;
        if(stats.intervalSeconds!==null)patch.interval=stats.intervalSeconds;
        if(stats.speedUnitsPerSecond!==null)patch.speed=Math.round(stats.speedUnitsPerSecond*1000)/1000;
        if(stats.rangeTiles!==null)patch.range=stats.rangeTiles*24;
        if(stats.sightRangeTiles!==null)patch.sightRange=stats.sightRangeTiles*24;
        if(stats.damagePerAttack!==null)patch.damage=stats.damagePerAttack/((card.burst||1)*(card.bolts||1));
        if(stats.shieldHp!==null)patch.shield=stats.shieldHp;
        if(stats.lifetimeSeconds!==null)patch.lifetime=stats.lifetimeSeconds;
        if(stats.count!==null&&stats.count>1)patch.count=stats.count;
        if(stats.splashRadiusTiles!==null&&card.splash)patch.splash=stats.splashRadiusTiles*24;
        if(stats.stunSeconds!==null)patch.stun=stats.stunSeconds;
        if(stats.spawnDamage!==null&&card.entryDamage)patch.entryDamage=stats.spawnDamage;
        if(stats.deathDamage!==null&&card.deathDamage)patch.deathDamage=stats.deathDamage;
        if(stats.spawnIntervalSeconds!==null&&card.summon)patch.summonEvery=stats.spawnIntervalSeconds;
        if(stats.spawnCount!==null&&card.summon)patch.summonCount=stats.spawnCount;
        if(stats.deathSpawnCount!==null&&card.deathSpawn)patch.deathCount=stats.deathSpawnCount;
        if(stats.projectileSpeedNative!==null&&card.range>=50)patch.projectileSpeed=stats.projectileSpeedNative*.48;
      }
    }else if(direct){
      if(stats.damagePerAttack!==null)patch.damage=stats.damagePerAttack;
      if(stats.crownTowerDamagePerHit!==null)patch.towerDamage=stats.crownTowerDamagePerHit*(stats.hitsPerAttack||1);
      if(stats.radiusTiles!==null)patch.splash=stats.radiusTiles*24;
      if(stats.stunSeconds!==null)patch.stun=stats.stunSeconds;
      if(stats.damagePerSecond!==null)patch.fieldDamage=stats.damagePerSecond;
      if(stats.crownTowerDamagePerSecond!==null)patch.fieldTowerDamage=stats.crownTowerDamagePerSecond;
      if(stats.durationSeconds!==null)patch[card.fieldDuration?'fieldDuration':'freeze']=stats.durationSeconds;
      if(stats.projectileSpeedNative!==null&&card.travelSpeed)patch.travelSpeed=stats.projectileSpeedNative*.48;
      if(card.rolling){patch.travelDistance=stats.rangeTiles*24;patch.splash=stats.widthTiles*12;}
    }
  }
  if(key==='pandilla'){patch.count=5;patch.deployTime=1;}
  if(key==='sneaselAmbush')Object.assign(patch,{spawnDeployTime:1.1,spawnTotal:3,travelSpeed:192});
  if(key==='sneaselToken')Object.assign(patch,{windup:.3,vulnerableDuringDeploy:true});
  if(key==='beedrill')delete patch.range; // Physical double sting, total damage budget is 107.
  if(key==='duskull')Object.assign(patch,{splash:36,summonCount:4,summonMax:12,deathSpawn:null,deathCount:0});
  if(key==='blizzard')patch.stun=stats.durationSeconds;
  if(key==='ampharos')patch.stun=0;
  if(Object.keys(patch).length)overrides[key]=patch;
  audit.push({key,reference:equivalent?.reference||null,similarity:equivalent?.similarity||'none',policy:direct?'Current reference body/attack budget, retaining documented Pokemon mechanics':stats?'Retain distinct Pokemon health, attack budget and role; update deployment, preparation and nominal movement tier':'Pokemon-specific body; normalize nominal movement and default deployment only',changes:patch,source:profile?.source||null,unknown:stats?Object.keys(stats).filter(k=>stats[k]===null):[],reason:equivalent?.reason||'Custom Pokemon mechanics'});
}
const header='// Generated by scripts/update-current-reference.mjs from the dated, attributed audit.\n// Arena: 24 units/tile; speed is millitiles per 50ms tick, not tiles/minute.\n';
fs.writeFileSync(new URL('../dist/current-reference.js',import.meta.url),header+'export const CURRENT_REFERENCE_BALANCE = '+JSON.stringify(overrides,null,2)+';\n');
fs.writeFileSync(new URL('../docs/BALANCE-AUDIT-2026-11-14.json',import.meta.url),JSON.stringify({asOf:source.asOf,level:11,coverage:audit.length,source:'CLASH-REFERENCE-2026-11-14.json',policy:'No invented values for unresolved fields. Custom roles and extra mechanics remain explicit adaptations, not claims of exact Clash Royale parity.',cards:audit},null,2)+'\n');
console.log(`Prepared ${audit.length} card audits; ${Object.keys(overrides).length} numeric profiles.`);
