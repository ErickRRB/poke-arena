"""Losslessly unpack archived GIFs for comparison, outside the shipped game.

This only changes the container and frame layout, not the sprite artwork.
"""
import json
from hashlib import sha256
from pathlib import Path
from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT/'artwork/sprite-sources'
OUTPUT = ROOT/'artwork/sprite-sources/retired-atlases'
OUTPUT.mkdir(exist_ok=True)
report = {}
for species, name in [(6,'charizard'),(149,'dragonite'),(18,'pidgeot'),(249,'lugia'),(334,'altaria'),(330,'flygon')]:
  report[species] = {}
  for view in ['front', 'back']:
    source = SOURCE/name/(view+'.gif')
    image = Image.open(source)
    width, height = image.size
    columns = 8
    atlas = Image.new('RGBA', (width*columns, height*((image.n_frames+columns-1)//columns)))
    durations = []
    for frame in range(image.n_frames):
        image.seek(frame)
        # GIF disposal is resolved by Pillow before each complete frame is copied.
        atlas.paste(image.convert('RGBA'), ((frame % columns)*width, (frame//columns)*height))
        durations.append(image.info['duration']/1000)
    filename = name+'-flight-'+view+'-v1.png'
    atlas.save(OUTPUT/filename, optimize=True)
    assert len(set(durations))==1, 'A variable-frame GIF needs explicit timing metadata.'
    report[species][view] = {'file':'assets/battle/'+filename, 'width':width, 'height':height,
                    'columns':columns, 'frames':len(durations), 'nativeFrameSeconds':durations[0], 'sha256':sha256(source.read_bytes()).hexdigest()}
(OUTPUT/'flight-atlases.js').write_text('// Lossless GIF frame layout. Generated by scripts/import-flight-sprites.py.\nexport const FLIGHT_ATLASES='+json.dumps(report,separators=(',',':'))+';\n',encoding='utf8')
print(json.dumps({species:{view:meta['frames'] for view,meta in views.items()} for species,views in report.items()}))
